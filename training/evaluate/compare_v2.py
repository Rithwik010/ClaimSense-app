"""The v2 evaluation (Part 2 step 6, D-POL-2): model v1 and model v2 on the same v2 test inputs
(data/generated/decision_v2/test_inputs.jsonl: claims, rules 2.x outcomes, v2 criteria), each with
the prompt it was trained on (model v1: decision_v2 re-rendered from the inputs; model v2: the
records' decision_v3), scored as the pipeline uses answers (one retry when invalid, decisions
derived from the statuses, D-DEC-1). Writes one results table to docs/results-v2.md.

Predictions go to data/generated/eval/v2/<label>.jsonl (a stopped run resumes); follow them with
`tail -f data/generated/eval/v2/<label>.log`.

    uv run python -m training.evaluate.compare_v2                       # both models
    uv run python -m training.evaluate.compare_v2 --only v1 --limit 5   # a quick check
"""

import argparse
import json
from pathlib import Path
from typing import Any

from training.evaluate.model import EVAL_DIR, run
from training.generate.decision_dataset_v2 import OUT_DIR as DATASET_V2
from training.generate.scenarios_v2 import TEST_ONLY_POLICIES, TEST_ONLY_STYLE

ROOT = Path(__file__).resolve().parents[2]
RESULTS_V2 = ROOT / "docs" / "results-v2.md"
OUT = EVAL_DIR / "v2"
MODELS = {
    "v1": ("claimsense-decision:v1", "decision_v2", "v2data-model-v1"),
    "v2": ("claimsense-decision:v2", "record", "v2data-model-v2"),
}


def table(reports: list[dict[str, Any]]) -> str:
    def f1(m: dict[str, Any], label: str) -> Any:
        return m["decisions"].get("per_class", {}).get(label, {}).get("f1")

    rows = [
        "| Model | Prompt | Records | Valid output | Retried | Line accuracy | Macro-F1 "
        "| F1 APPROVE | F1 PEND | F1 DENY | Criterion status | Evidence quoted "
        f"| Unseen policies | Style {TEST_ONLY_STYLE} (held out) | Styles A-C | Claim decision "
        "| Latency p50 (ms) |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for r in reports:
        m = r["metrics"]
        groups = m["groups"]
        others = [
            g
            for k, g in groups.items()
            if k.startswith("style:") and k != f"style:{TEST_ONLY_STYLE}"
        ]
        other_lines = sum(g["records"] for g in others)
        other_accuracy = (
            round(sum(g["line_accuracy"] * g["records"] for g in others) / other_lines, 4)
            if other_lines
            else None
        )
        rows.append(
            f"| {r['model']} | {r['prompt']} | {m['records']} | {m['valid_output_rate']} | "
            f"{r.get('retried_records', 0)} | {m['decisions'].get('accuracy')} | "
            f"{m['decisions'].get('macro_f1')} | {f1(m, 'APPROVE')} | {f1(m, 'PEND')} | "
            f"{f1(m, 'DENY')} | {m['criterion_status_accuracy']} | {m['evidence_quoted_rate']} | "
            f"{groups.get('unseen_policies', {}).get('line_accuracy')} | "
            f"{groups.get(f'style:{TEST_ONLY_STYLE}', {}).get('line_accuracy')} | "
            f"{other_accuracy} | {m['claim_decision_accuracy']} | {m['latency_ms']['p50']} |"
        )
    dataset = reports[0]["dataset"] if reports else {}
    return "\n".join(
        [
            "# Results: model v1 and model v2 on the v2 test set",
            "",
            "Generated by `training/evaluate/compare_v2.py`; do not edit by hand. Both models",
            "see the same 300 v2 test inputs (policy set v2, rules 2.x), each with the prompt it",
            "was trained on; answers are used as the pipeline uses them (one retry when invalid,",
            "decisions derived from the statuses, D-DEC-1). Target (P4.4): macro-F1 >= 0.90 on",
            f"line decisions. Unseen policies: {sorted(TEST_ONLY_POLICIES)}. Style",
            f"{TEST_ONLY_STYLE} is a note style no training record uses; styles A-C are the",
            "training styles. Line accuracy columns are per group; F1 is per class over every",
            "line.",
            "",
            *rows,
            "",
            f"Dataset: `{json.dumps(dataset, sort_keys=True)}`",
            "",
        ]
    )


def main() -> None:
    from app.core.settings import get_settings
    from app.ml.client import OllamaDecisionModel

    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--only", choices=tuple(MODELS))
    parser.add_argument("--limit", type=int)
    args = parser.parse_args()
    settings = get_settings()
    import httpx

    version = httpx.get(f"{settings.ollama_url}/api/version", timeout=10).json()["version"]
    reports = []
    for key, (name, prompt, label) in MODELS.items():
        if args.only and key != args.only:
            existing = OUT / f"{label}.json"
            if existing.exists():
                reports.append(json.loads(existing.read_text()))
            continue
        report = run(
            OllamaDecisionModel(settings.ollama_url, name),
            label + (f"-limit{args.limit}" if args.limit else ""),
            dataset_dir=DATASET_V2,
            out_dir=OUT,
            limit=args.limit,
            engine=f"ollama {version}",
            prompt=prompt,
            test_only=set(TEST_ONLY_POLICIES),
        )
        reports.append(report)
        metrics = report["metrics"]
        print(
            name,
            json.dumps(
                {
                    "macro_f1": metrics["decisions"].get("macro_f1"),
                    "valid": metrics["valid_output_rate"],
                }
            ),
        )
    if not args.limit:
        RESULTS_V2.write_text(table(reports), encoding="utf-8")
        print(f"wrote {RESULTS_V2.relative_to(ROOT)}")
    else:
        print(table(reports))


if __name__ == "__main__":
    main()
