def test_kaggle_folder_needs_real_retrieval_and_is_private(tmp_path) -> None:  # noqa: ANN001
    from training.finetune.prepare_kaggle import DATASET_SLUG, prepare

    decision = tmp_path / "decision"
    decision.mkdir()
    for split in ("train", "validation", "test"):
        (decision / f"{split}.jsonl").write_text("{}\n")
    (decision / "summary.json").write_text(json.dumps({"retrieval": "simulated"}))
    with pytest.raises(SystemExit, match="simulated retrieval"):
        prepare(decision, tmp_path / "kaggle", "someone")

    (decision / "summary.json").write_text(json.dumps({"retrieval": "top 3; knowledge abc"}))
    dataset = prepare(decision, tmp_path / "kaggle", "someone")

    metadata = json.loads((dataset / "dataset-metadata.json").read_text())
    assert metadata["isPrivate"] is True and metadata["id"] == f"someone/{DATASET_SLUG}"
    assert {p.name for p in (dataset / "finetune").iterdir()} == {"train.py", "data.py"}
    notebook = json.loads((tmp_path / "kaggle" / "claimsense-finetune.ipynb").read_text())
    sources = ["".join(c["source"]) for c in notebook["cells"] if c["cell_type"] == "code"]
    assert any("glob.glob" in s and "train.jsonl" in s for s in sources)  # finds any mount path
    assert any(s.startswith("!python {TRAIN} --data {DATA}") for s in sources)
    namespace: dict = {}
    cell = next(s for s in sources if "SMOKE = True" in s)
    exec(cell[cell.index("\nSMOKE = True") :], namespace)  # the smoke-test settings only
    assert namespace["EXTRA"] == "--limit 50 --epochs 1 --eval-limit 20 --eval-steps 3 --no-gguf"

    export = next(s for s in sources if "--export-from" in s)
    assert "if not glob.glob(f'{OUT}/gguf/*.gguf'):" in export  # never exports twice

    renamed = prepare(decision, tmp_path / "kaggle", "someone", slug="claimsense")
    assert json.loads((renamed / "dataset-metadata.json").read_text())["id"] == "someone/claimsense"


def test_kaggle_v2_package_checks_the_dataset_and_writes_a_zip(tmp_path) -> None:  # noqa: ANN001
    import zipfile

    from training.finetune.prepare_kaggle import V2, prepare

    decision = tmp_path / "decision_v2"
    decision.mkdir()
    for split in ("train", "validation", "test"):
        (decision / f"{split}.jsonl").write_text("{}\n")
    summary = {"retrieval": "exact lookup v2", "prompt_version": "decision_v2", "policy_set": "v2"}
    (decision / "summary.json").write_text(json.dumps({**summary, "checks": {"problems": 0}}))
    with pytest.raises(SystemExit, match="not a v2 dataset"):
        prepare(decision, tmp_path / "kaggle", "someone", V2["slug"], version=2)

    summary["prompt_version"] = "decision_v3"
    (decision / "summary.json").write_text(json.dumps({**summary, "checks": {"problems": 0}}))
    dataset = prepare(decision, tmp_path / "kaggle", "someone", V2["slug"], version=2)

    assert dataset.name == V2["slug"]
    names = set(zipfile.ZipFile(tmp_path / "kaggle" / f"{V2['slug']}.zip").namelist())
    assert {"train.jsonl", "finetune/train.py", "dataset-metadata.json"} <= names
    notebook = json.loads((tmp_path / "kaggle" / V2["notebook"]).read_text())
    text = "".join("".join(c["source"]) for c in notebook["cells"])
    assert V2["out"] in text and "decision_v3" in text


class TextTokenizer:
    def __call__(self, text: str, add_special_tokens: bool = True) -> dict:
        return {"input_ids": ([2] if add_special_tokens else []) + [7] * len(text.split())}


class Processor:
    """Like Gemma 4's multimodal processor: a batch of one, and the text tokenizer inside."""

    tokenizer = TextTokenizer()

    def __call__(self, text: str, add_special_tokens: bool = True) -> dict:
        return {"input_ids": [self.tokenizer(text, add_special_tokens)["input_ids"]]}


def test_token_count_uses_the_text_tokenizer_of_a_processor() -> None:
    assert token_count(TextTokenizer(), "one two three") == 4
    assert token_count(Processor(), "one two three") == 4  # not 1 (the batch size)


