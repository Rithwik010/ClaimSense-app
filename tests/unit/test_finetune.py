"""Fine-tuning helpers (P4.3, P4.5) that run without a GPU: chat conversion, turn markers, length
report, the Kaggle folder and the Ollama Modelfile. The training itself runs only on Kaggle."""

import json

import jinja2
import pytest

from training.finetune.data import (
    CONFIG,
    length_report,
    supports_system_role,
    to_chat,
    turn_markers,
)
from training.finetune.modelfile import base_directives, build

# A Gemma-style template without a system role (it raises on one, like Gemma's own template).
GEMMA_LIKE = jinja2.Template(
    "<bos>{% for m in messages %}"
    "{% if m.role == 'system' %}{{ raise_error('System role not supported') }}{% endif %}"
    "<start_of_turn>{{ 'model' if m.role == 'assistant' else 'user' }}\n"
    "{{ m.content }}<end_of_turn>\n{% endfor %}"
    "{% if add_generation_prompt %}<start_of_turn>model\n{% endif %}"
)
WITH_SYSTEM = jinja2.Template(
    "{% for m in messages %}<|{{ m.role }}|>\n{{ m.content }}\n{% endfor %}"
    "{% if add_generation_prompt %}<|assistant|>\n{% endif %}"
)


def raise_error(message: str) -> None:
    raise ValueError(message)


def gemma_like(messages, add_generation_prompt: bool) -> str:  # noqa: ANN001
    return GEMMA_LIKE.render(
        messages=messages, add_generation_prompt=add_generation_prompt, raise_error=raise_error
    )


def with_system(messages, add_generation_prompt: bool) -> str:  # noqa: ANN001
    return WITH_SYSTEM.render(messages=messages, add_generation_prompt=add_generation_prompt)


MESSAGES = [
    {"role": "system", "content": "Rules."},
    {"role": "user", "content": "Claim."},
    {"role": "assistant", "content": '{"lines": []}'},
]


def test_system_instructions_move_into_the_first_user_turn_when_needed() -> None:
    assert not supports_system_role(gemma_like)
    assert supports_system_role(with_system)

    merged = to_chat(MESSAGES, system_role=False)

    assert [m["role"] for m in merged] == ["user", "assistant"]
    assert merged[0]["content"] == "Rules.\n\nClaim."
    assert to_chat(MESSAGES, system_role=True) == MESSAGES
    assert "<start_of_turn>user\nRules.\n\nClaim.<end_of_turn>" in gemma_like(merged, False)


def test_turn_markers_come_from_the_template() -> None:
    assert turn_markers(gemma_like) == ("<start_of_turn>user\n", "<start_of_turn>model\n")
    assert turn_markers(with_system) == ("<|user|>\n", "<|assistant|>\n")


def test_length_report_counts_records_over_the_maximum() -> None:
    report = length_report([100, 2000, 3100, 900], max_len=3072)

    assert report["max"] == 3100 and report["over_max"] == 1 and report["records"] == 4


def test_config_follows_the_section_10_starting_point() -> None:
    assert CONFIG["lora_r"] == 16 and CONFIG["lora_dropout"] == 0.0
    assert CONFIG["learning_rate"] == 2e-4 and CONFIG["gradient_accumulation_steps"] == 8
    assert CONFIG["load_in_4bit"] and not CONFIG["finetune_vision_layers"]
    assert CONFIG["gguf_quantization"] == "q4_k_m"


def test_modelfile_copies_the_base_chat_handling(tmp_path) -> None:  # noqa: ANN001
    base = (
        "# Modelfile generated by ollama show\nFROM /blobs/sha256-abc\nTEMPLATE {{ .Prompt }}\n"
        'RENDERER gemma4\nPARSER gemma4\nPARAMETER top_k 64\nLICENSE """Apache"""\n'
    )
    gguf = tmp_path / "model.Q4_K_M.gguf"

    text = build(gguf, base)

    assert text.splitlines() == [
        f"FROM {gguf.resolve()}",
        "TEMPLATE {{ .Prompt }}",
        "RENDERER gemma4",
        "PARSER gemma4",
        "PARAMETER top_k 64",
    ]
    assert base_directives("FROM x\nLICENSE y") == []


def test_kaggle_folder_needs_real_retrieval_and_is_private(tmp_path) -> None:  # noqa: ANN001
    from training.finetune.prepare_kaggle import DATASET_SLUG, prepare

    decision = tmp_path / "decision"
    decision.mkdir()
    for split in ("train", "validation", "test"):
        (decision / f"{split}.jsonl").write_text("{}\n")
    (decision / "summary.json").write_text(json.dumps({"retrieval": "simulated"}))
    with pytest.raises(SystemExit, match="simulated retrieval"):
        prepare(decision, tmp_path / "kaggle", "someone")

    (decision / "summary.json").write_text(json.dumps({"retrieval": "top 3; knowledge abc"}))
    dataset = prepare(decision, tmp_path / "kaggle", "someone")

    metadata = json.loads((dataset / "dataset-metadata.json").read_text())
    assert metadata["isPrivate"] is True and metadata["id"] == f"someone/{DATASET_SLUG}"
    assert {p.name for p in (dataset / "finetune").iterdir()} == {"train.py", "data.py"}
    notebook = json.loads((tmp_path / "kaggle" / "claimsense-finetune.ipynb").read_text())
    sources = ["".join(c["source"]) for c in notebook["cells"] if c["cell_type"] == "code"]
    assert any("glob.glob" in s and "train.jsonl" in s for s in sources)  # finds any mount path
    assert any(s.startswith("!python {TRAIN} --data {DATA}") for s in sources)
    namespace: dict = {}
    cell = next(s for s in sources if "SMOKE = True" in s)
    exec(cell[cell.index("\nSMOKE = True") :], namespace)  # the smoke-test settings only
    assert namespace["EXTRA"] == "--limit 50 --epochs 1 --no-gguf"

    renamed = prepare(decision, tmp_path / "kaggle", "someone", slug="claimsense")
    assert json.loads((renamed / "dataset-metadata.json").read_text())["id"] == "someone/claimsense"
