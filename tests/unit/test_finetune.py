# A Gemma-style template without a system role (it raises on one, like Gemma's own template).
GEMMA_LIKE = jinja2.Template(
    "<bos>{% for m in messages %}"
    "{% if m.role == 'system' %}{{ raise_error('System role not supported') }}{% endif %}"
    "<start_of_turn>{{ 'model' if m.role == 'assistant' else 'user' }}\n"
    "{{ m.content }}<end_of_turn>\n{% endfor %}"
    "{% if add_generation_prompt %}<start_of_turn>model\n{% endif %}"
)
WITH_SYSTEM = jinja2.Template(
    "{% for m in messages %}<|{{ m.role }}|>\n{{ m.content }}\n{% endfor %}"
    "{% if add_generation_prompt %}<|assistant|>\n{% endif %}"
)


def raise_error(message: str) -> None:
    raise ValueError(message)


def gemma_like(messages, add_generation_prompt: bool) -> str:  # noqa: ANN001
    return GEMMA_LIKE.render(
        messages=messages, add_generation_prompt=add_generation_prompt, raise_error=raise_error
    )


def with_system(messages, add_generation_prompt: bool) -> str:  # noqa: ANN001
    return WITH_SYSTEM.render(messages=messages, add_generation_prompt=add_generation_prompt)


MESSAGES = [
    {"role": "system", "content": "Rules."},
    {"role": "user", "content": "Claim."},
    {"role": "assistant", "content": '{"lines": []}'},
]


def test_system_instructions_move_into_the_first_user_turn_when_needed() -> None:
    assert not supports_system_role(gemma_like)
    assert supports_system_role(with_system)

    merged = to_chat(MESSAGES, system_role=False)

    assert [m["role"] for m in merged] == ["user", "assistant"]
    assert merged[0]["content"] == "Rules.\n\nClaim."
    assert to_chat(MESSAGES, system_role=True) == MESSAGES
    assert "<start_of_turn>user\nRules.\n\nClaim.<end_of_turn>" in gemma_like(merged, False)


def test_turn_markers_come_from_the_template() -> None:
    assert turn_markers(gemma_like) == ("<start_of_turn>user\n", "<start_of_turn>model\n")
    assert turn_markers(with_system) == ("<|user|>\n", "<|assistant|>\n")


